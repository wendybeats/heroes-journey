#!/usr/bin/env python3
"""Write an HTML inventory of the doc 33 content drafts (challenges, held lines, repeat exchanges, pages, story
lines, rumours) from Content/v1/drafts/between-beats.json, for the owner's edit pass.
    python3 Tools/export_between_beats_inventory.py [Content/v1/drafts/between-beats.json] [out.html]
"""
import html, json, sys
src = sys.argv[1] if len(sys.argv) > 1 else "Content/v1/drafts/between-beats.json"
out_path = sys.argv[2] if len(sys.argv) > 2 else "between-beats-inventory.html"
d = json.load(open(src))
e = html.escape
names = {"guide.elder": "Cairon", "hero": "Hero"}
names.update({c["id"]: c["display_name"] for c in d["characters"]})
who = lambda s: names.get(s, s)
def beats(bs): return "".join(f"<li><b>{e(who(b['speaker']))}:</b> " + " / ".join(e(l) for l in b["lines"]) + "</li>" for b in bs)

out = [f"""<title>Between the Beats Drafts</title>
<style>
/* Layout: one column; each section a table keyed by stable id; navy ground, gold for the thing being tested. */
:root {{ --bg:#0B1020; --surface:#121A30; --line:#26314F; --fg:#E9ECF5; --muted:#9AA5C4; --gold:#E3B65A; --warn:#F08A6B;
  --mono: ui-monospace,"SF Mono",Menlo,Consolas,monospace; --sans:"Barlow",-apple-system,"Segoe UI",system-ui,sans-serif; color-scheme: dark; }}
@media (prefers-color-scheme: light) {{ :root:not([data-theme="dark"]) {{ --bg:#F3F4F8; --surface:#FFF; --line:#D7DBE8; --fg:#121A30; --muted:#56607F; --gold:#9A6F12; --warn:#B8441F; color-scheme: light }} }}
:root[data-theme="light"] {{ --bg:#F3F4F8; --surface:#FFF; --line:#D7DBE8; --fg:#121A30; --muted:#56607F; --gold:#9A6F12; --warn:#B8441F; color-scheme: light }}
body {{ background:var(--bg); color:var(--fg); font:15px/1.5 var(--sans); margin:0; padding-block:32px 64px; padding-inline:16px; }}
main {{ max-width:1040px; margin:0 auto; display:grid; gap:40px; }}
h1 {{ font-size:28px; margin:0 0 4px; text-wrap:balance }} h2 {{ font-size:20px; margin:0; padding-top:8px; border-top:1px solid var(--line) }}
h3 {{ font-size:15px; margin:20px 0 8px; color:var(--muted); text-transform:uppercase; letter-spacing:.08em; font-weight:600 }}
p.lede {{ color:var(--muted); margin:0; max-width:65ch }} .meta {{ font-family:var(--mono); font-size:12px; color:var(--muted) }}
.wrap {{ overflow-x:auto }} table {{ border-collapse:collapse; width:100%; font-size:14px }}
th {{ text-align:left; color:var(--muted); font-weight:600; font-size:12px; text-transform:uppercase; letter-spacing:.06em; padding:8px 10px; border-bottom:1px solid var(--line) }}
td {{ padding:9px 10px; border-bottom:1px solid var(--line); vertical-align:top; min-width:0 }}
td.copy {{ min-width:24ch }} .gold {{ color:var(--gold) }} .count {{ color:var(--gold); font-variant-numeric:tabular-nums }}
ul {{ margin:4px 0 0; padding-left:18px }} li {{ margin:2px 0 }} .pill {{ font-family:var(--mono); font-size:11px; text-transform:uppercase; letter-spacing:.06em; padding:2px 6px; border:1px solid currentColor; border-radius:3px; white-space:nowrap }}
</style>
<main>
<header><h1>Between the Beats Drafts</h1>
<p class="lede">First drafts of every line the doc 33 systems need: challenges with their aftermath exchanges, the lines that hold a beat for its quest, repeat quest exchanges, the found pages, story-aware goal lines and Row rumours. Ids are final; the words are for your edit pass, REPLACE / KEEP / CUT as before.</p>
<p class="meta">Content/v1/drafts/between-beats.json · generated by Tools/export_between_beats_inventory.py</p></header>
"""]

# Characters
out.append("<section><h2>0 · Unnamed challengers <span class='count'>%d</span></h2><div class='wrap'><table><tr><th>Id</th><th>Shown as</th><th>Notes</th></tr>" % len(d["characters"]))
for c in d["characters"]: out.append(f"<tr><td class='meta'>{e(c['id'])}</td><td><b>{e(c['display_name'])}</b></td><td>{e(c['notes'])}</td></tr>")
out.append("</table></div></section>")

# Challenges
out.append(f"<section><h2>1 · Challenges <span class='count'>{len(d['challenges'])}</span></h2><p class='lede'>Card: name, the attribute tested, the difficulty word and the challenger's dialogue portrait. Then the clash, the result card, and the aftermath exchange.</p>")
for c in d["challenges"]:
    gate = c.get("available_after_quest") or c.get("available_after_milestone") or f"Level {c.get('available_from_level')}"
    out.append(f"<h3>{e(c['name'])} · {e(who(c['character_id']))} · <span class='gold'>{e(c['attribute_id'])}</span> · {e(c['difficulty'])}</h3><p class='meta'>{e(c['id'])} · available after {e(gate)} · {e(c['area_id'])}</p>")
    out.append("<div class='wrap'><table><tr><th>Set</th><th>Offer</th><th>Win</th><th>Lose</th><th>Aftermath · win</th><th>Aftermath · lose</th></tr>")
    for k, s in enumerate(c["sets"], 1):
        out.append(f"<tr><td>{k}</td><td class='copy'>{e(s['offer'])}</td><td class='copy'>{e(s['win'])}</td><td class='copy'>{e(s['lose'])}</td><td class='copy'><ul>{beats(s['aftermath_win'])}</ul></td><td class='copy'><ul>{beats(s['aftermath_lose'])}</ul></td></tr>")
    out.append("</table></div>")
out.append("</section>")

# Held lines + Ascension II
out.append("<section><h2>2 · Beats that wait for their quest <span class='count'>%d</span></h2><p class='lede'>Shown on the goals card while the beat is held.</p><div class='wrap'><table><tr><th>Milestone</th><th>Waits for</th><th>Line (Cairon)</th></tr>" % len(d["held_lines"]))
for h in d["held_lines"]: out.append(f"<tr><td class='meta'>{e(h['milestone'])}</td><td class='meta'>{e(h['requires_quest'])}</td><td class='copy'>{e(h['line'])}</td></tr>")
out.append("</table></div>")
for ch in d["story_chapters"]:
    out.append(f"<h3>{e(ch['title'])} · after the tier-2 takeover</h3><p class='meta'>{e(ch['id'])} · {e(ch['backdrop_id'])} · evolution {e(ch['evolution'])}</p><ul>{beats(ch['beats'])}</ul>")
out.append("</section>")

# Repeat exchanges
n = sum(len(v) for v in d["repeat_exchanges"].values())
out.append(f"<section><h2>3 · Repeat quest exchanges <span class='count'>{n}</span></h2><p class='lede'>Play on the second, third… claimed completion of a quest, in order, then cycle.</p>")
for q, xs in d["repeat_exchanges"].items():
    out.append(f"<h3>{e(q)}</h3>")
    for k, x in enumerate(xs, 2): out.append(f"<p class='meta'>completion {k}</p><ul>{beats(x)}</ul>")
out.append("</section>")

# Pages
out.append(f"<section><h2>4 · Found pages <span class='count'>{len(d['pages'])}</span></h2><p class='lede'>Colossus's log, one line a page, dropped from the Gym quests. The Room shows them in order.</p><div class='wrap'><table><tr><th>Id</th><th>Name</th><th>Line</th></tr>")
for p in d["pages"]: out.append(f"<tr><td class='meta'>{e(p['id'])}</td><td><b>{e(p['display_name'])}</b></td><td class='copy'>{e(p['description'])}</td></tr>")
out.append("</table></div></section>")

# Story lines
out.append(f"<section><h2>5 · Story-aware goal lines <span class='count'>{sum(len(s['lines']) for s in d['story_lines'])}</span></h2><p class='lede'>Rare alternates (about one in ten) once the trigger has happened. Your examples kept.</p><div class='wrap'><table><tr><th>Goal</th><th>After</th><th>Lines</th></tr>")
for s in d["story_lines"]: out.append(f"<tr><td class='meta'>{e(s['goal'])}</td><td class='meta'>{e(s['after'])}</td><td class='copy'><ul>" + "".join(f"<li>{e(l)}</li>" for l in s["lines"]) + "</ul></td></tr>")
out.append("</table></div></section>")

# Rumours
out.append(f"<section><h2>6 · Row rumours <span class='count'>{len(d['rumours'])}</span></h2><p class='lede'>One a day on the goals card's rest-day line, from the pool the story has unlocked.</p><div class='wrap'><table><tr><th>After</th><th>Rumour</th></tr>")
for r in d["rumours"]: out.append(f"<tr><td class='meta'>{e(r['after'])}</td><td class='copy'>{e(r['text'])}</td></tr>")
out.append("</table></div></section></main>")
open(out_path, "w").write("\n".join(out))
print("wrote", out_path)
